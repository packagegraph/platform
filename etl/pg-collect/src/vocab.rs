    /// Map the namespace constants in uris.rs (`PKG`, `RPM`, ...) to their URIs
    /// by parsing uris.rs, so this never drifts from the real definitions.
    fn namespace_map(src: &Path) -> HashMap<String, String> {
        let text = fs::read_to_string(src.join("uris.rs")).expect("read uris.rs");
        let mut map = HashMap::new();
        for line in text.lines() {
            let line = line.trim();
            let Some(rest) = line.strip_prefix("pub const ") else {
                continue;
            };
            let Some((name, value)) = rest.split_once(": &str = ") else {
                continue;
            };
            let uri = value.trim().trim_end_matches(';').trim_matches('"');
            if uri.starts_with("https://purl.org/packagegraph/") && uri.ends_with('#') {
                map.insert(name.trim().to_string(), uri.to_string());
            }
        }
        assert!(
            map.contains_key("PKG"),
            "did not find the PKG namespace constant in uris.rs"
        );
        map
    }

    /// Extract every `format!("{PREFIX}Term")` occurrence from the crate source.
    ///
    /// Only whole-string forms count: the term must run from the prefix to the
    /// closing quote. Collectors also build *instance* URIs from the same
    /// namespaces -- `format!("{TAX}audience-{slug}")`,
    /// `format!("{PKG}match-repology-{id}")` -- and those name individuals the
    /// data creates, not vocabulary the ontology is expected to declare.
    /// Requiring the closing quote is what separates the two.
    fn emitted_terms(src: &Path, ns: &HashMap<String, String>) -> HashSet<String> {
        let mut out = HashSet::new();
        let mut files: Vec<_> = Vec::new();
        collect_rs(src, &mut files);
        for f in files {
            // This file quotes `{PKG}fooBar` in its own documentation.
            if f.file_name().is_some_and(|n| n == "vocab.rs") {
                continue;
            }
            let text = fs::read_to_string(&f).expect("read source file");
            for (idx, _) in text.match_indices("{") {
                let tail = &text[idx + 1..];
                let Some(close) = tail.find('}') else { continue };
                let prefix = &tail[..close];
                let Some(base) = ns.get(prefix) else { continue };
                let after = &tail[close + 1..];
                let end = after
                    .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                    .unwrap_or(after.len());
                if end == 0 || after.as_bytes().get(end) != Some(&b'"') {
                    continue;
                }
                out.insert(format!("{base}{}", &after[..end]));
            }
        }
        out
    }

    fn collect_rs(dir: &Path, out: &mut Vec<std::path::PathBuf>) {
        for e in fs::read_dir(dir).expect("read_dir") {
            let p = e.expect("dir entry").path();
            if p.is_dir() {
                collect_rs(&p, out);
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push(p);
            }
        }
    }

    fn declared() -> HashSet<String> {
        let manifest = Path::new(env!("CARGO_MANIFEST_DIR")).join("ontology-vocab.txt");
        let text = fs::read_to_string(&manifest).unwrap_or_else(|e| {
            panic!(
                "cannot read {}: {e}. Regenerate with etl/scripts/gen-ontology-vocab.py",
                manifest.display()
            )
        });
        text.lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .map(str::to_string)
            .collect()
    }

    #[test]
    fn every_emitted_term_is_declared_by_the_ontology() {
        let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let ns = namespace_map(&src);
        let declared = declared();
        let known: HashSet<&str> = KNOWN_UNDECLARED.iter().copied().collect();

        let mut undeclared: Vec<String> = emitted_terms(&src, &ns)
            .into_iter()
            .filter(|t| !declared.contains(t) && !known.contains(t.as_str()))
            .collect();
        undeclared.sort();

        assert!(
            undeclared.is_empty(),
            "{} ontology term(s) are emitted but not declared by the ontology.\n\n{}\n\n\
             Either declare them in packagegraph/ontology and regenerate \
             etl/pg-collect/ontology-vocab.txt, or stop emitting them. Do NOT add them to \
             KNOWN_UNDECLARED -- that list only shrinks.",
            undeclared.len(),
            undeclared.join("\n")
        );
    }

    /// The ratchet only holds if its baseline stays accurate: an entry that has
    /// since been declared (or is no longer emitted) must be removed, or the
    /// list silently stops being a to-do and starts being noise.
    #[test]
    fn known_undeclared_list_has_no_stale_entries() {
        let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let ns = namespace_map(&src);
        let declared = declared();
        let emitted = emitted_terms(&src, &ns);

        let now_declared: Vec<&str> = KNOWN_UNDECLARED
            .iter()
            .copied()
            .filter(|t| declared.contains(*t))
            .collect();
        let no_longer_emitted: Vec<&str> = KNOWN_UNDECLARED
            .iter()
            .copied()
            .filter(|t| !emitted.contains(*t))
            .collect();

        assert!(
            now_declared.is_empty(),
            "these are now declared by the ontology -- remove them from KNOWN_UNDECLARED:\n{}",
            now_declared.join("\n")
        );
        assert!(
            no_longer_emitted.is_empty(),
            "these are no longer emitted -- remove them from KNOWN_UNDECLARED:\n{}",
            no_longer_emitted.join("\n")
        );
    }
