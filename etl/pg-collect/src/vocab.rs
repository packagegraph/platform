    /// Writer methods whose argument 2 is an RDF object (so the term names a
    /// class or an individual). Every other `write_*` method puts a literal
    /// there, which is not a term.
    const OBJECT_ARG_METHODS: &[&str] = &[
        "write_triple",
        "write_triple_once",
        "write_bnode_subject",
        "write_bnode_to_bnode",
        "write_bnode_object",
    ];

    /// Map the namespace constants in uris.rs (`PKG`, `RPM`, ...) to their URIs
    /// by parsing uris.rs, so this never drifts from the real definitions.
    fn namespace_map(src: &Path) -> HashMap<String, String> {
        let text = fs::read_to_string(src.join("uris.rs")).expect("read uris.rs");
        let mut map = HashMap::new();
        for line in text.lines() {
            let Some(rest) = line.trim().strip_prefix("pub const ") else {
                continue;
            };
            let Some((name, value)) = rest.split_once(": &str = ") else {
                continue;
            };
            let uri = value.trim().trim_end_matches(';').trim_matches('"');
            if uri.starts_with("https://purl.org/packagegraph/") && uri.ends_with('#') {
                map.insert(name.trim().to_string(), uri.to_string());
            }
        }
        assert!(
            map.contains_key("PKG"),
            "did not find the PKG namespace constant in uris.rs"
        );
        map
    }

    /// Remove `#[cfg(test)]` items by brace matching, so test-only references
    /// are not counted as emitted vocabulary.
    fn strip_test_modules(text: &str) -> String {
        let mut out = String::with_capacity(text.len());
        let mut rest = text;
        while let Some(pos) = rest.find("#[cfg(test)]") {
            out.push_str(&rest[..pos]);
            let after = &rest[pos..];
            // Skip to the opening brace of the item, then past its matching close.
            let Some(open) = after.find('{') else { break };
            let mut depth = 0usize;
            let mut end = None;
            for (i, c) in after[open..].char_indices() {
                match c {
                    '{' => depth += 1,
                    '}' => {
                        depth -= 1;
                        if depth == 0 {
                            end = Some(open + i + 1);
                            break;
                        }
                    }
                    _ => {}
                }
            }
            match end {
                Some(e) => rest = &after[e..],
                None => break,
            }
        }
        out.push_str(rest);
        out
    }

    /// Split a call's argument list on top-level commas, respecting nesting and
    /// string literals.
    fn split_args(s: &str) -> Vec<String> {
        let mut args = Vec::new();
        let mut cur = String::new();
        let (mut depth, mut in_str, mut esc) = (0i32, false, false);
        for c in s.chars() {
            if in_str {
                cur.push(c);
                if esc {
                    esc = false;
                } else if c == '\\' {
                    esc = true;
                } else if c == '"' {
                    in_str = false;
                }
                continue;
            }
            match c {
                '"' => {
                    in_str = true;
                    cur.push(c);
                }
                '(' | '[' | '{' => {
                    depth += 1;
                    cur.push(c);
                }
                ')' | ']' | '}' => {
                    depth -= 1;
                    cur.push(c);
                }
                ',' if depth == 0 => {
                    args.push(cur.trim().to_string());
                    cur = String::new();
                }
                _ => cur.push(c),
            }
        }
        if !cur.trim().is_empty() {
            args.push(cur.trim().to_string());
        }
        args
    }

    /// Pull the single `{PREFIX}Term` a whole-string `format!` argument builds,
    /// if that is what this argument is.
    fn term_of(arg: &str, ns: &HashMap<String, String>) -> Option<String> {
        let open = arg.find('{')?;
        let close = arg[open..].find('}')? + open;
        let base = ns.get(&arg[open + 1..close])?;
        let after = &arg[close + 1..];
        let end = after
            .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .unwrap_or(after.len());
        // Must run to the closing quote, or it is an instance URI, not a term.
        if end == 0 || after.as_bytes().get(end) != Some(&b'"') {
            return None;
        }
        Some(format!("{base}{}", &after[..end]))
    }

    /// Every (term, usage) pair this crate emits.
    ///
    /// Two passes, because neither alone is both complete and role-aware:
    /// a positional pass over writer call sites yields roles, and a whole-file
    /// pass yields every term including those assembled away from their call
    /// site. Terms only the second pass finds are recorded as
    /// [`UsedAs::Unknown`] rather than dropped.
    fn emitted(src: &Path, ns: &HashMap<String, String>) -> HashSet<(String, UsedAs)> {
        let mut out = HashSet::new();
        let mut all_terms: HashSet<String> = HashSet::new();
        let mut files = Vec::new();
        collect_rs(src, &mut files);
        for f in files {
            if f.file_name().is_some_and(|n| n == "vocab.rs") {
                continue;
            }
            let text = strip_test_modules(&fs::read_to_string(&f).expect("read source"));

            // Pass 2 (completeness): any whole-string `format!("{PREFIX}Term")`
            // anywhere in the file, wherever it is later used.
            for (idx, _) in text.match_indices('{') {
                let tail = &text[idx..];
                if let Some(t) = term_of(tail, ns) {
                    all_terms.insert(t);
                }
            }

            // Pass 1 (roles): writer call sites, by argument position.
            for (idx, _) in text.match_indices(".write_") {
                let tail = &text[idx + 1..];
                let Some(paren) = tail.find('(') else { continue };
                let method = &tail[..paren];
                if !method
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || c == '_')
                {
                    continue;
                }
                // Balanced extraction of the argument list.
                let body = &tail[paren + 1..];
                let (mut depth, mut in_str, mut esc, mut end) = (1i32, false, false, None);
                for (i, c) in body.char_indices() {
                    if in_str {
                        if esc {
                            esc = false;
                        } else if c == '\\' {
                            esc = true;
                        } else if c == '"' {
                            in_str = false;
                        }
                        continue;
                    }
                    match c {
                        '"' => in_str = true,
                        '(' | '[' | '{' => depth += 1,
                        ')' | ']' | '}' => {
                            depth -= 1;
                            if depth == 0 {
                                end = Some(i);
                                break;
                            }
                        }
                        _ => {}
                    }
                }
                let Some(e) = end else { continue };
                let args = split_args(&body[..e]);
                if args.len() < 2 {
                    continue;
                }
                // Argument 1 is the predicate for every write_* method.
                if let Some(t) = term_of(&args[1], ns) {
                    out.insert((t, UsedAs::Property));
                }
                if args.len() >= 3 && OBJECT_ARG_METHODS.contains(&method) {
                    if let Some(t) = term_of(&args[2], ns) {
                        let role = if args[1].contains("RDF_TYPE") {
                            UsedAs::Class
                        } else {
                            UsedAs::Value
                        };
                        out.insert((t, role));
                    }
                }
            }
        }

        // Anything the completeness pass found but no call site explained.
        let positioned: HashSet<&String> = out.iter().map(|(t, _)| t).collect();
        let unknown: Vec<String> = all_terms
            .iter()
            .filter(|t| !positioned.contains(t))
            .cloned()
            .collect();
        for t in unknown {
            out.insert((t, UsedAs::Unknown));
        }
        out
    }

    fn collect_rs(dir: &Path, out: &mut Vec<PathBuf>) {
        for e in fs::read_dir(dir).expect("read_dir") {
            let p = e.expect("dir entry").path();
            if p.is_dir() {
                collect_rs(&p, out);
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push(p);
            }
        }
    }

    /// Parse the role-annotated manifest.
    fn declared() -> HashMap<String, HashSet<String>> {
        let manifest = Path::new(env!("CARGO_MANIFEST_DIR")).join("ontology-vocab.txt");
        let text = fs::read_to_string(&manifest).unwrap_or_else(|e| {
            panic!(
                "cannot read {}: {e}. Regenerate with etl/scripts/gen-ontology-vocab.py",
                manifest.display()
            )
        });
        let mut out = HashMap::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (uri, roles) = line
                .split_once('\t')
                .unwrap_or_else(|| panic!("manifest line is not <uri>\\t<roles>: {line}"));
            out.insert(
                uri.to_string(),
                roles.split(',').map(|r| r.trim().to_string()).collect(),
            );
        }
        assert!(!out.is_empty(), "manifest parsed to zero terms");
        out
    }

    #[test]
    fn every_emitted_term_is_declared_in_the_role_it_is_used_in() {
        let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let ns = namespace_map(&src);
        let declared = declared();
        let known: HashSet<(&str, &str)> = KNOWN_BAD.iter().copied().collect();
        let empty = HashSet::new();

        let mut bad: Vec<String> = emitted(&src, &ns)
            .into_iter()
            .filter(|(uri, used)| {
                let roles = declared.get(uri).unwrap_or(&empty);
                !used.satisfied_by(roles) && !known.contains(&(uri.as_str(), used.label()))
            })
            .map(|(uri, used)| {
                let roles = declared.get(&uri).unwrap_or(&empty);
                if roles.is_empty() {
                    format!("{uri}\n    used as {}, but not declared at all", used.label())
                } else {
                    let mut have: Vec<_> = roles.iter().cloned().collect();
                    have.sort();
                    format!(
                        "{uri}\n    used as {}, but the ontology declares it only as {}",
                        used.label(),
                        have.join(", ")
                    )
                }
            })
            .collect();
        bad.sort();

        assert!(
            bad.is_empty(),
            "{} ontology term(s) are emitted in a role the ontology does not declare.\n\n{}\n\n\
             Either declare them in packagegraph/ontology and regenerate \
             etl/pg-collect/ontology-vocab.txt, or stop emitting them that way. Do NOT add \
             them to KNOWN_BAD -- that list only shrinks.",
            bad.len(),
            bad.join("\n")
        );
    }

    /// The ratchet only holds if its baseline stays accurate: an entry that has
    /// since been declared, or is no longer emitted that way, must be removed,
    /// or the list stops being a to-do and becomes noise.
    #[test]
    fn known_bad_list_has_no_stale_entries() {
        let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let ns = namespace_map(&src);
        let declared = declared();
        let emitted = emitted(&src, &ns);
        let empty = HashSet::new();

        let mut stale = Vec::new();
        for (uri, used_label) in KNOWN_BAD {
            let used = match *used_label {
                "property" => UsedAs::Property,
                "class" => UsedAs::Class,
                "value" => UsedAs::Value,
                "unknown-role" => UsedAs::Unknown,
                other => panic!("KNOWN_BAD has an unknown usage role {other:?} for {uri}"),
            };
            if !emitted.contains(&(uri.to_string(), used)) {
                stale.push(format!("{uri} ({used_label}) -- no longer emitted that way"));
            } else if used.satisfied_by(declared.get(*uri).unwrap_or(&empty)) {
                stale.push(format!("{uri} ({used_label}) -- now declared in that role"));
            }
        }
        stale.sort();

        assert!(
            stale.is_empty(),
            "{} stale KNOWN_BAD entr(ies) -- remove them:\n{}",
            stale.len(),
            stale.join("\n")
        );
    }
