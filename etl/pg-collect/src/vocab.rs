//! Gate: every ontology term this crate emits must be declared by the ontology,
//! in the role the emitting code uses it in.
//!
//! The collectors build predicate and class URIs as `format!("{PKG}fooBar")`,
//! hundreds of times across the tree. Nothing connected those strings to the
//! ontology, so a typo and a deliberately invented predicate looked identical,
//! and neither failed anything. `rpm:rpmProvides` reached 6,558,436 triples
//! that no consumer can discover from the published ontology.
//!
//! This module closes that loop at `cargo test` time by scanning the crate's
//! own source for writer calls, resolving each namespace prefix via the
//! constants in `uris.rs`, and checking the resulting URI against
//! `ontology-vocab.txt` (generated by `etl/scripts/gen-ontology-vocab.py`).
//!
//! ## Roles, not just spellings
//!
//! The first version of this gate compared bare URIs, which answered "is this
//! string declared?" but not "is it declared as the kind of thing you are
//! using it as?". `rpm:RPMGroup` slipped through on exactly that distinction:
//! it is a declared `owl:Class`, and `rpm.rs` and `emit/rpm_ext.rs` write it as
//! a literal predicate. A membership test calls that fine; it is 523,728
//! triples asserting a class URI as a property.
//!
//! So argument position decides what is required:
//!
//! | Position | Required role |
//! |---|---|
//! | predicate (arg 1 of every `write_*`) | `property` |
//! | object of `RDF_TYPE` | `class` |
//! | any other object | `class` or `individual` |
//!
//! ## Scope of the scan
//!
//! Only whole-string forms count: `format!("{PKG}packageName")` where the term
//! runs from the prefix to the closing quote. Collectors also build *instance*
//! URIs from these namespaces -- `format!("{TAX}audience-{slug}")` -- and those
//! name individuals the data creates, not vocabulary the ontology declares.
//!
//! `#[cfg(test)]` modules are skipped. Terms referenced only from test
//! fixtures are not emitted into any graph, and counting them overstates what
//! the collectors actually produce.
//!
//! It is a ratchet, not a clean bill of health: what was already wrong when
//! this landed is listed in `KNOWN_BAD` so the gate can pass today while
//! refusing anything new. Each entry is annotated with what is actually wrong
//! with it, so the list is the work queue.

