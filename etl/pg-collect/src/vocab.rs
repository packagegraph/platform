//! Gate: every ontology term this crate emits must be declared by the ontology.
//!
//! The collectors build predicate and class URIs as `format!("{PKG}fooBar")`,
//! 926 times across the tree. Nothing connected those strings to the ontology,
//! so a typo and a deliberately invented predicate looked identical, and
//! neither failed anything. The 2026-09-11 production audit found 28
//! properties and 2 classes emitted at volume that the ontology never
//! declares -- `rpm:rpmProvides` alone is 6,558,436 triples that no consumer
//! can discover from the published ontology.
//!
//! This module closes that loop at `cargo test` time by scanning the crate's
//! own source for those `format!` patterns, resolving the namespace prefix via
//! the constants in `uris.rs`, and checking each resulting URI against
//! `ontology-vocab.txt` (generated by `etl/scripts/gen-ontology-vocab.py`).
//!
//! Scanning source rather than querying the graph doubled the count, to 60:
//! the graph only shows terms whose code path actually ran in a production
//! collection, so every undeclared term behind an unrun branch was invisible.
//! It also exposed a class the graph cannot show at all -- six terms whose
//! local name IS declared, but in another module and scoped by `rdfs:domain`
//! to a different class, so the emission is wrong even though the name
//! resolves. `vcs:hasRelease` is the clearest: `core:hasRelease` exists, with
//! domain `:Distribution` and range `:DistributionRelease` -- Debian 12, not a
//! GitHub release. Those are annotated in `KNOWN_UNDECLARED` below; none of
//! them is fixable by swapping the prefix.
//!
//! It is a ratchet, not a clean bill of health: the terms already undeclared
//! when this landed are listed in `KNOWN_UNDECLARED` so the gate can pass
//! today while refusing anything new. Shrinking that list is tracked in
//! `docs/reports/2026-09-11-ontology-conformance-and-coverage-audit.md`.

