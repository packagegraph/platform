    /// How a term is being used at a call site, which is what determines the
    /// role the ontology has to declare.
    #[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
    enum UsedAs {
        /// Predicate position: the ontology must declare a property.
        Property,
        /// Object of `rdf:type`: the ontology must declare a class.
        Class,
        /// Any other object position: a class or an individual will do.
        Value,
        /// The term is built away from its writer call -- into a variable, a
        /// lookup table, or a struct field -- so its role cannot be read off a
        /// call site. `debian.rs:965` is the case that forced this: the
        /// `deb:debDepends` family is assembled in a dependency-kind table and
        /// passed to `write_triple` through a variable, so a purely positional
        /// scan reports 1.46M triples' worth of predicates as absent.
        ///
        /// These are checked for declaration only. That is a genuinely weaker
        /// check, and it is named rather than hidden: this gate does not claim
        /// role coverage it does not have.
        Unknown,
    }

    impl UsedAs {
        fn label(self) -> &'static str {
            match self {
                UsedAs::Property => "property",
                UsedAs::Class => "class",
                UsedAs::Value => "value",
                UsedAs::Unknown => "unknown-role",
            }
        }

        fn satisfied_by(self, roles: &HashSet<String>) -> bool {
            match self {
                UsedAs::Property => roles.contains("property"),
                UsedAs::Class => roles.contains("class"),
                UsedAs::Value => roles.contains("class") || roles.contains("individual"),
                UsedAs::Unknown => !roles.is_empty(),
            }
        }
    }

